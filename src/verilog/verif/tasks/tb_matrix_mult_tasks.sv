/******************************************************************************
 File Name : tb_matrix_mult_tasks.sv
 Description :
     Test sequences for tb_matrix_mult (memory mode, tiled across K and N).
     Included inside the tb_matrix_mult module so the tasks can drive its
     signals and reach the memory emulators hierarchically.

     Memory images use the tiled layout from gen_golden.py: one tile row per
     word, and each 4-wide column strip is a contiguous block of words. With
     K = N = 4 (one tile) this is the milestone 1b layout.

     Flow for every test listed in <testdir>/tests.list
     (generated by scripts/gen_golden.py from src/Simulator):
       1. Reset the DUT, fill the input/weight memories with X and the
          output memory with a poison value
       2. $readmemh ACT_MEM.hex / WEIGHT_MEM.hex at the configured offsets
       3. Compute an SV reference result from the loaded memories (16-bit
          saturating accumulation across K tiles, then 8-bit saturation)
       4. Pulse start_i, wait for done_o (with a timeout)
       5. Check done_o stays high, compare every output lane with the golden
          OUTPUT_MEM.hex, check sign extension and that no other output row
          was written, and write dut.log (same format as golden.log)

     Directed tests then cover the start/done handshake, restarting from DONE
     (including switching between tiled and single-tile shapes), memory
     offsets, reset in every cycle of a run, and start_i already high when
     reset is released.

     The debug add-on test steps through every debug page during a run
     (debug_obs_checker compares each one), then reads the pages in DONE and
     checks them against values computed from the test (counts, weight
     checksum, saturation flags), and checks that a start edge and a reset
     clear them.

     Plusargs:
       +testdir=<dir>   directory holding tests.list (default: tests)
       +test=<name>     only run this test from tests.list
       +no_directed     skip the directed tests
       +debug_only      run only the debug add-on test (debug_obs_pages) after the golden test
*******************************************************************************/

localparam int DONE_HOLD_CYCLES = 20;   // cycles done_o is checked to stay high after it rises
localparam int OP_MAX = (1 <<< (WIDTH-1)) - 1;
localparam int OP_MIN = -(1 <<< (WIDTH-1));
localparam int M_TWO_TILES = 2 * Tm;

// Output memory fill value. A sign-extended 8-bit result can never equal it, so any row still
// holding it was never written. (A value is used instead of X so 2-state simulators work too.)
localparam logic [Tn*ACCUM_WIDTH-1:0] OB_POISON = {Tn{ACCUM_WIDTH'(16'hDEAD)}};
localparam int M_MID_LO    = 3 * Tm;
localparam int M_MID_HI    = MAX_ROW - Tm;
localparam int MAX_K_TILES = MAX_ROW / Tk;
localparam int MAX_N_TILES = MAX_COL / Tn;
localparam int MAX_O_WORDS = MAX_ROW * MAX_N_TILES;  // output words of the largest (64x64) result
localparam int PSUM_MAX    = (1 <<< (ACCUM_WIDTH-1)) - 1;
localparam int PSUM_MIN    = -(1 <<< (ACCUM_WIDTH-1));

// One entry of tests.list
typedef struct {
    string  name;
    int     m, n, k;
} test_t;

string  test_dir;
int     n_tests_run;
int     n_tests_failed;
int     n_golden_errors;
int     last_errors;            // errors from the most recent run_memory_test
int     last_latency;           // start edge to done_o, in cycles, from the most recent run_memory_test
bit     ref_sat16, ref_sat8;    // the current test saturates a 16-bit partial sum / an 8-bit output
bit     debug_sweep = 1'b0;     // step extra_config_i every cycle (debug add-on test)

// Golden output image (16-bit lanes like the output memory, tiled layout) and SV reference result for the current test
logic [Tn*ACCUM_WIDTH-1:0]  golden_mem [MAX_O_WORDS];
logic signed [WIDTH-1:0]    ref_out    [MAX_ROW][MAX_COL];

// ---------------------------------------------------------------- Stimulus coverage
// Every (activation, weight) pair multiplied by the test set
covergroup cg_operands with function sample(int a, int b);
    cp_a: coverpoint a {
        bins min       = {OP_MIN};
        bins neg       = {[OP_MIN+1:-2]};
        bins minus_one = {-1};
        bins zero      = {0};
        bins one       = {1};
        bins pos       = {[2:OP_MAX-1]};
        bins max       = {OP_MAX};
    }
    cp_b: coverpoint b {
        bins min       = {OP_MIN};
        bins neg       = {[OP_MIN+1:-2]};
        bins minus_one = {-1};
        bins zero      = {0};
        bins one       = {1};
        bins pos       = {[2:OP_MAX-1]};
        bins max       = {OP_MAX};
    }
    x_ab: cross cp_a, cp_b;
endgroup

// How each run was configured and started
covergroup cg_test with function sample(int m, int k_tiles, int n_tiles, bit offsets, int start_hold, bit from_done);
    cp_m: coverpoint m {
        bins one_tile  = {Tm};
        bins two_tiles = {M_TWO_TILES};
        bins mid       = {[M_MID_LO:M_MID_HI]};
        bins max_rows  = {MAX_ROW};
    }
    cp_k_tiles: coverpoint k_tiles {
        bins one   = {1};
        bins two   = {2};
        bins mid   = {[3:MAX_K_TILES-1]};
        bins max   = {MAX_K_TILES};
    }
    cp_n_tiles: coverpoint n_tiles {
        bins one   = {1};
        bins two   = {2};
        bins mid   = {[3:MAX_N_TILES-1]};
        bins max   = {MAX_N_TILES};
    }
    x_k_n: cross cp_k_tiles, cp_n_tiles;
    cp_offsets: coverpoint offsets {
        bins zero    = {0};
        bins nonzero = {1};
    }
    cp_start: coverpoint start_hold {
        bins held_forever = {0};
        bins one_cycle    = {1};
        bins multi_cycle  = {[2:$]};
    }
    cp_from: coverpoint from_done {
        bins after_reset = {0};
        bins after_done  = {1};
    }
endgroup

// Partial sum after each K tile (before the next tile is added), when K has more than one tile
covergroup cg_psum with function sample(longint psum);
    cp_psum: coverpoint psum {
        bins sat_low  = {[$:PSUM_MIN-1]};
        bins min      = {PSUM_MIN};
        bins in_range = {[PSUM_MIN+1:PSUM_MAX-1]};
        bins max      = {PSUM_MAX};
        bins sat_high = {[PSUM_MAX+1:$]};
    }
endgroup

cg_operands cg_operands_inst = new();
cg_test     cg_test_inst     = new();
cg_psum     cg_psum_inst     = new();

// ---------------------------------------------------------------- Helpers
function automatic int num_tiles(int n, int k);
    return (k / Tk) * (n / Tn);
endfunction

// Each tile is LOAD_WEIGHT (Tk) + STREAM (m) + DRAIN (about Tm + Tn); allow 4x that
function automatic int timeout_cycles(int m, int n, int k);
    return 4 * num_tiles(n, k) * (Tk + m + Tm + Tn) + 100;
endfunction

function automatic int saturate_int(longint value, int bits);
    longint hi = (longint'(1) <<< (bits-1)) - 1;
    longint lo = -(longint'(1) <<< (bits-1));
    if (value > hi) return int'(hi);
    if (value < lo) return int'(lo);
    return int'(value);
endfunction

task automatic init_tb_signals();
    rst_n         = 1'b0;
    start_i       = 1'b0;
    en_i          = 1'b0;
    ext_en_i      = 1'b0;
    ext_inputs_i  = '0;
    test_config_i = '0;
    data_config_i = '0;
    write_files   = 1'b1;
endtask

task automatic reset_dut(input int cycles = 5);
    @(negedge clk_i);
    rst_n   = 1'b0;
    start_i = 1'b0;
    repeat (cycles) @(negedge clk_i);
    rst_n   = 1'b1;
    @(negedge clk_i);
endtask

task automatic configure(input int m, input int n, input int k, input int i_off, input int w_off, input int p_off);
    data_config_i             = '0;
    data_config_i.i_rows      = m;
    data_config_i.w_rows      = k;
    data_config_i.w_cols      = n;
    data_config_i.i_offset    = i_off;
    data_config_i.w_offset    = w_off;
    data_config_i.psum_offset = p_off;
endtask

// Element accessors for the tiled layout. A[r][c] is in strip c/Tk at word strip*m + r,
// B[r][c] is in strip c/Tn at word strip*k + r, and C[r][c] is in strip c/Tn at word strip*m + r.
function automatic int mem_a(int r, int c, int m, int i_off);
    return $signed(ib_mem.data[i_off + (c / Tk) * m + r][(c % Tk)*WIDTH +: WIDTH]);
endfunction

function automatic int mem_b(int r, int c, int k, int w_off);
    return $signed(wb_mem.data[w_off + (c / Tn) * k + r][(c % Tn)*WIDTH +: WIDTH]);
endfunction

function automatic int c_addr(int r, int c, int m);
    return (c / Tn) * m + r;
endfunction

// SV reference result from the memory contents, independent of the C simulator. Full precision
// inside a K tile, 16-bit saturating partial sum across K tiles, 8-bit saturation at the end.
function automatic void compute_reference(int m, int n, int k, int i_off, int w_off);
    ref_sat16 = 1'b0;
    ref_sat8  = 1'b0;
    for (int r = 0; r < m; r++) begin
        for (int c = 0; c < n; c++) begin
            longint psum = 0;
            for (int k0 = 0; k0 < k; k0 += Tk) begin
                longint tile = 0;
                for (int kk = k0; kk < k0 + Tk; kk++) begin
                    int a = mem_a(r, kk, m, i_off);
                    int b = mem_b(kk, c, k, w_off);
                    tile += a * b;
                    cg_operands_inst.sample(a, b);
                end
                if (k0 + Tk < k) cg_psum_inst.sample(psum + tile);
                if (k0 + Tk < k && saturate_int(psum + tile, ACCUM_WIDTH) != psum + tile) ref_sat16 = 1'b1;
                psum = saturate_int(psum + tile, ACCUM_WIDTH);
            end
            if (saturate_int(psum, WIDTH) != psum) ref_sat8 = 1'b1;
            ref_out[r][c] = WIDTH'(saturate_int(psum, WIDTH));
        end
    end
endfunction

// Fill the input/weight memories with X and the output memory with OB_POISON, then load the
// test's memory images at the given offsets
task automatic load_test(input test_t t, input int i_off, input int w_off);
    string base = {test_dir, "/", t.name, "/"};

    for (int a = 0; a < I_SIZE; a++) ib_mem.data[a] = 'x;
    for (int a = 0; a < W_SIZE; a++) wb_mem.data[a] = 'x;
    for (int a = 0; a < O_SIZE; a++) ob_mem.data[a] = OB_POISON;
    for (int a = 0; a < MAX_O_WORDS; a++) golden_mem[a] = 'x;

    $readmemh({base, "ACT_MEM.hex"},    ib_mem.data, i_off, i_off + t.m * (t.k / Tk) - 1);
    $readmemh({base, "WEIGHT_MEM.hex"}, wb_mem.data, w_off, w_off + t.k * (t.n / Tn) - 1);
    $readmemh({base, "OUTPUT_MEM.hex"}, golden_mem,  0,     t.m * (t.n / Tn) - 1);

    compute_reference(t.m, t.n, t.k, i_off, w_off);
endtask

// Wait for done_o to rise. When a run is restarted from DONE, done_o must drop first.
task automatic wait_for_done(input test_t t, output int cycles, output bit timed_out);
    bit seen_low = !done_o;
    cycles    = 0;
    timed_out = 1'b0;
    forever begin
        @(negedge clk_i);
        cycles++;
        if (!done_o)        seen_low = 1'b1;
        else if (seen_low)  break;
        if (cycles >= timeout_cycles(t.m, t.n, t.k)) begin
            timed_out = 1'b1;
            break;
        end
    end
endtask

// Compare the output memory with the golden image and write dut.log
task automatic check_results(input test_t t, input int p_off, output int errors);
    int                         fd;
    int                         stray_rows = 0;
    int                         o_words = t.m * (t.n / Tn);
    int                         addr;
    string                      line;
    logic [ACCUM_WIDTH-1:0]     got;
    logic [ACCUM_WIDTH-1:0]     exp;

    errors = 0;
    fd = $fopen({test_dir, "/", t.name, "/dut.log"}, "w");
    if (fd != 0) $fdisplay(fd, "# test=%s M=%0d N=%0d", t.name, t.m, t.n);

    for (int r = 0; r < t.m; r++) begin
        line = $sformatf("ROW %0d:", r);
        for (int c = 0; c < t.n; c++) begin
            addr = c_addr(r, c, t.m);
            got  = ob_mem.data[p_off + addr][(c % Tn)*ACCUM_WIDTH +: ACCUM_WIDTH];
            exp  = golden_mem[addr][(c % Tn)*ACCUM_WIDTH +: ACCUM_WIDTH];
            line = {line, $sformatf(" %02X", got[WIDTH-1:0])};

            // The C simulator golden and the SV reference must agree, or the test itself is wrong
            if (exp !== ACCUM_WIDTH'(ref_out[r][c])) begin
                n_golden_errors++;
                $error("[%s] golden C[%0d][%0d] = %04X but SV reference = %04X", t.name, r, c, exp,
                       ACCUM_WIDTH'(ref_out[r][c]));
            end

            if (got[WIDTH-1:0] !== exp[WIDTH-1:0]) begin
                errors++;
                $error("[%s] C[%0d][%0d]: DUT %02X, expected %02X (output mem addr %0d, lane %0d)",
                       t.name, r, c, got[WIDTH-1:0], exp[WIDTH-1:0], p_off + addr, c % Tn);
            end else if (CHECK_SIGN_EXT && got !== exp) begin
                errors++;
                $error("[%s] C[%0d][%0d]: DUT lane %04X, expected %04X (upper bits not the sign extension)",
                       t.name, r, c, got, exp);
            end
        end
        if (fd != 0) $fdisplay(fd, "%s", line);
    end
    if (fd != 0) $fclose(fd);

    // Rows outside the output window must still hold OB_POISON (never written)
    for (int a = 0; a < O_SIZE; a++)
        if ((a < p_off || a >= p_off + o_words) && ob_mem.data[a] !== OB_POISON) stray_rows++;
    if (stray_rows != 0) begin
        errors++;
        $error("[%s] %0d output memory rows outside [%0d, %0d) were written", t.name, stray_rows, p_off, p_off + o_words);
    end
endtask

function automatic void report_test(string tag, test_t t, int errors, int latency);
    n_tests_run++;
    if (errors != 0) n_tests_failed++;
    $display("[%s] %-40s MxKxN=%0dx%0dx%0d latency=%0d cycles", (errors != 0) ? "FAIL" : "PASS",
             tag, t.m, t.k, t.n, latency);
endfunction

// ---------------------------------------------------------------- One memory-mode run
//   start_hold : cycles start_i stays high (0 = leave it high; the caller lowers it)
//   do_reset   : reset first (0 = run from the current IDLE/DONE state)
task automatic run_memory_test(input test_t t,
                               input int    i_off      = 0,
                               input int    w_off      = 0,
                               input int    p_off      = 0,
                               input int    start_hold = 1,
                               input bit    do_reset   = 1,
                               input string label      = "",
                               input bit    busy_start = 0);
    string  tag = (label == "") ? t.name : {label, " (", t.name, ")"};
    int     errors = 0;
    int     check_errors;
    int     latency;
    bit     timed_out;
    bit     from_done;

    if (do_reset) reset_dut();
    from_done = done_o;

    load_test(t, i_off, w_off);
    configure(t.m, t.n, t.k, i_off, w_off, p_off);

    @(negedge clk_i);
    start_i = 1'b1;
    fork
        begin
            if (start_hold > 0) begin
                repeat (start_hold) @(negedge clk_i);
                start_i = 1'b0;
                if (busy_start) begin
                    repeat (Tk+1) @(negedge clk_i);
                    start_i = 1'b1;
                    repeat (2) @(negedge clk_i);
                    start_i = 1'b0;
                end
            end
        end
        wait_for_done(t, latency, timed_out);
    join

    if (timed_out) begin
        errors++;
        $error("[%s] timed out after %0d cycles waiting for done_o", tag, latency);
    end else begin
        // done_o must stay high until the next start edge
        for (int c = 0; c < DONE_HOLD_CYCLES; c++) begin
            @(negedge clk_i);
            if (!done_o) begin
                errors++;
                $error("[%s] done_o dropped %0d cycles after rising without a new start edge", tag, c + 1);
                break;
            end
        end
    end

    check_results(t, p_off, check_errors);
    errors += check_errors;

    last_errors  = errors;
    last_latency = latency;
    report_test(tag, t, errors, latency);
    cg_test_inst.sample(t.m, t.k / Tk, t.n / Tn, (i_off != 0) || (w_off != 0) || (p_off != 0), start_hold, from_done);
endtask

// ---------------------------------------------------------------- Directed tests
// Reset the DUT at every cycle of a run. After each reset done_o must be low and stay low
// (the assertions also check that the memories stay idle). Then a clean run must still pass.
task automatic reset_sweep(input test_t t);
    int errors = 0;
    int run_len;

    run_memory_test(t, .label("reset_sweep_reference"));
    run_len = last_latency;

    for (int d = 1; d <= run_len; d++) begin
        reset_dut();
        load_test(t, 0, 0);
        configure(t.m, t.n, t.k, 0, 0, 0);
        @(negedge clk_i);
        start_i = 1'b1;
        @(negedge clk_i);
        start_i = 1'b0;
        repeat (d - 1) @(negedge clk_i);

        rst_n = 1'b0;
        repeat (2) @(negedge clk_i);
        if (done_o) begin
            errors++;
            $error("[reset_sweep] done_o high during reset (reset %0d cycles into the run)", d);
        end
        rst_n = 1'b1;

        for (int c = 0; c < run_len + 10; c++) begin
            @(negedge clk_i);
            if (done_o) begin
                errors++;
                $error("[reset_sweep] done_o rose after reset with no new start edge (reset %0d cycles into the run)", d);
                break;
            end
        end
    end
    report_test($sformatf("reset_sweep x%0d (%s)", run_len, t.name), t, errors, run_len);

    // No extra reset: the DUT must work straight out of the last swept reset
    run_memory_test(t, .do_reset(1'b0), .label("run_after_reset_sweep"));
endtask

// start_i is already high when reset is released. There is no rising edge, so the DUT
// must not start. Lowering and raising start_i afterwards must start a normal run.
task automatic start_high_through_reset(input test_t t);
    int errors = 0;

    @(negedge clk_i);
    rst_n   = 1'b0;
    start_i = 1'b1;
    load_test(t, 0, 0);
    configure(t.m, t.n, t.k, 0, 0, 0);
    repeat (5) @(negedge clk_i);
    rst_n = 1'b1;

    for (int c = 0; c < timeout_cycles(t.m, t.n, t.k); c++) begin
        @(negedge clk_i);
        if (done_o || !ib_mem_cenb_o || !wb_mem_cenb_o) begin
            errors++;
            $error("[start_high_through_reset] DUT started without a rising edge on start_i (start_i was already high at reset release)");
            break;
        end
    end
    report_test($sformatf("start_high_through_reset (%s)", t.name), t, errors, 0);

    // If the DUT did start, let that run finish so the next start edge does not land mid-run
    if (errors != 0)
        for (int c = 0; c < timeout_cycles(t.m, t.n, t.k) && !done_o; c++) @(negedge clk_i);

    @(negedge clk_i);
    start_i = 1'b0;
    run_memory_test(t, .do_reset(1'b0), .label("edge_after_start_high_reset"));
endtask

// ---------------------------------------------------------------- Debug add-on
// While debug_sweep is set, step extra_config_i (fp_en and obs_sel) every cycle, so
// debug_obs_checker compares every page during a real run
always @(negedge clk_i) if (debug_sweep) data_config_i.extra_config_i <= data_config_i.extra_config_i + 1'b1;

// Allow a full clock period for the combinational debug mux and routed delays to settle.
task automatic read_page(input int sel, input bit fp_en, output logic [7:0] page);
    data_config_i.extra_config_i = {3'(sel), fp_en};
    #(CLOCK_PERIOD);
    page = extra_output_bits_o.extra_config_o;
endtask

task automatic check_page(input string tag, input int sel, input logic [7:0] exp, inout int errors,
                          input bit fp_en = 1'b0);
    logic [7:0] got;
    read_page(sel, fp_en, got);
    if (got !== exp) begin
        errors++;
        $error("[%s] debug page %0d = %02X, expected %02X", tag, sel, got, exp);
    end
endtask

// Pages after a reset: everything is 0 except last_k on page 3, which follows data_config_i
task automatic check_debug_cleared(input string tag, input test_t t, inout int errors);
    for (int p = 0; p < 8; p++)
        check_page(tag, p, (p == 3) ? {t.k == Tk, 7'd0} : 8'h00, errors);
endtask

// Pages in DONE after a run of t (weights loaded from w_off = 0)
task automatic check_debug_after_run(input string tag, input test_t t, inout int errors);
    int                 rows = t.m * num_tiles(t.n, t.k);
    logic [WIDTH-1:0]   wxor = '0;

    // The array still holds the last weight tile: the last K tile of the last N strip
    for (int r = t.k - Tk; r < t.k; r++)
        for (int j = 0; j < Tn; j++)
            wxor ^= wb_mem.data[(t.n / Tn - 1) * t.k + r][j*WIDTH +: WIDTH];

    // Status: start seen, done, state DONE. With fp_en set it is echoed in bit 5
    check_page(tag, 0, {1'b0, 1'b1, 1'b0, 1'b0, 1'b1, 3'(controller_fsm_pkg::DONE)}, errors);
    check_page(tag, 0, {1'b0, 1'b1, 1'b1, 1'b0, 1'b1, 3'(controller_fsm_pkg::DONE)}, errors, 1'b1);
    // The tile and read counters are cleared in DONE, the write counter holds i_rows
    check_page(tag, 1, 8'h00, errors);
    check_page(tag, 2, 8'h00, errors);
    check_page(tag, 3, {t.k == Tk, 7'(t.m)}, errors);
    check_page(tag, 4, 8'(wxor), errors);
    // One input row and one output row per activation row per tile (wraps at 256)
    check_page(tag, 5, 8'(rows), errors);
    check_page(tag, 6, 8'(rows), errors);
    check_page(tag, 7, {3'b111, 3'b000, ref_sat8, ref_sat16}, errors);
endtask

task automatic debug_obs_test(input test_t t_sat, input test_t t_clean);
    int errors = 0;

    // Reset clears every counter and flag, and the PE weights (so the checksum is 0)
    reset_dut();
    configure(t_sat.m, t_sat.n, t_sat.k, 0, 0, 0);
    check_debug_cleared("debug_after_reset", t_sat, errors);

    // Every page, every cycle, during a run that saturates. run_memory_test checks the
    // results, so switching pages mid-run must not disturb the computation
    debug_sweep = 1'b1;
    run_memory_test(t_sat, .label("debug_page_sweep"));
    debug_sweep = 1'b0;
    @(negedge clk_i);
    check_debug_after_run("debug_after_first_run", t_sat, errors);

    // Restart from DONE with different data: the start edge clears the counters and
    // flags (start seen stays set), so the pages only show the second run
    run_memory_test(t_clean, .do_reset(1'b0), .label("debug_restart_from_done"));
    check_debug_after_run("debug_after_restart", t_clean, errors);

    // Reset clears everything again, including start seen
    reset_dut();
    check_debug_cleared("debug_after_second_reset", t_clean, errors);

    report_test($sformatf("debug_obs_pages (%s, %s)", t_sat.name, t_clean.name), t_sat, errors, 0);
endtask

task automatic run_directed_tests(input test_t tests[$]);
    // Pick tests with non-trivial data for the directed scenarios, falling back to the first test
    test_t  t_a = tests[0], t_b = tests[0], t_long, t_tile, t_tile_big;
    bit     has_long = 0, has_tile = 0, has_tile_big = 0;
    test_t  t_sat = tests[0];

    foreach (tests[i]) begin
        if (tests[i].name == "rand_small_0")           t_a = tests[i];
        if (tests[i].name == "rand_full_0")            t_b = tests[i];
        if (tests[i].name == "stream_M64_full")        begin t_long     = tests[i]; has_long     = 1; end
        if (tests[i].name == "tile_M8_K8_N8_full")     begin t_tile     = tests[i]; has_tile     = 1; end
        if (tests[i].name == "tile_M36_K12_N8_med")    begin t_tile_big = tests[i]; has_tile_big = 1; end
        if (tests[i].name == "psum_sat16_pos")         t_sat = tests[i];
    end

    $display("\n---------------- Directed tests ----------------");

    // start_i held high for the whole run and after it: one run only, done_o stays high
    run_memory_test(t_a, .start_hold(0), .label("start_held_high"));
    for (int c = 0; c < 50; c++) begin
        @(negedge clk_i);
        if (!done_o) begin
            $error("[start_held_high] done_o dropped while start_i stayed high");
            n_tests_failed++;
            break;
        end
    end
    start_i = 1'b0;

    // start_i held high for several cycles
    run_memory_test(t_b, .start_hold(5), .label("start_multi_cycle"));

    run_memory_test(t_a, .busy_start(1), .label("busy_start_ignored"));
    if (has_tile)
        run_memory_test(t_tile, .busy_start(1), .label("tiled_busy_start_ignored"));

    // Back-to-back runs with new data, restarting from DONE without a reset
    run_memory_test(t_a, .label("restart_first"));
    run_memory_test(t_b, .do_reset(1'b0), .label("restart_from_done"));
    run_memory_test(t_a, .do_reset(1'b0), .label("restart_from_done_again"));

    // data_config_i offsets (the spec allows 0, but the offsets exist for tiling)
    run_memory_test(t_b, .i_off(17), .w_off(300), .p_off(513), .label("nonzero_offsets"));
    if (has_long)
        run_memory_test(t_long, .i_off(I_SIZE - t_long.m), .w_off(W_SIZE - Tk),
                        .p_off(O_SIZE - t_long.m), .label("offsets_at_top_of_memory"));

    if (has_tile) begin
        // start_i held high through a multi-tile run (it must not restart between tiles)
        run_memory_test(t_tile, .start_hold(0), .label("tiled_start_held_high"));
        start_i = 1'b0;

        // Restart from DONE while switching between tiled and single-tile shapes. The tile
        // counters and offsets must start from 0 again on every run.
        run_memory_test(t_tile, .label("tiled_restart_first"));
        run_memory_test(t_b,    .do_reset(1'b0), .label("tiled_then_single_tile"));
        run_memory_test(t_tile, .do_reset(1'b0), .label("single_tile_then_tiled"));
        run_memory_test(t_tile, .do_reset(1'b0), .label("tiled_restart_from_done"));

        // Offsets with tiling: every strip is placed relative to its offset
        run_memory_test(t_tile, .i_off(101), .w_off(37), .p_off(250), .label("tiled_nonzero_offsets"));
    end
    if (has_tile_big)
        run_memory_test(t_tile_big, .i_off(I_SIZE - t_tile_big.m * (t_tile_big.k / Tk)),
                        .w_off(W_SIZE - t_tile_big.k * (t_tile_big.n / Tn)),
                        .p_off(O_SIZE - t_tile_big.m * (t_tile_big.n / Tn)), .label("tiled_offsets_at_top_of_memory"));

    // Reset in every cycle of a run (single tile, then a run with several K and N tiles so the
    // reset also lands in the DRAIN -> LOAD_WEIGHT tile transitions)
    reset_sweep(t_a);
    if (has_tile) reset_sweep(t_tile);

    // start_i already high at reset release
    start_high_through_reset(t_b);

    // Debug add-on pages (psum_sat16_pos saturates both 16 and 8 bits; rand_small never saturates)
    debug_obs_test(t_sat, t_a);
endtask

