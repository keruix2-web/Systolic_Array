task automatic run_all_tests();
    test_t  tests[$];
    string  name, only;
    int     fd, m, n, k;

    if (!$value$plusargs("testdir=%s", test_dir)) test_dir = "tests";
    if (!$value$plusargs("test=%s", only))        only     = "";

    fd = $fopen({test_dir, "/tests.list"}, "r");
    if (fd == 0) $fatal(1, "Cannot open %s/tests.list. Run 'make golden' first.", test_dir);
    while ($fscanf(fd, "%s %d %d %d\n", name, m, n, k) == 4) begin
        if (only == "" || only == name) begin
            if (m % Tm != 0 || n % Tn != 0 || k % Tk != 0 || m > MAX_ROW || n > MAX_COL || k > MAX_ROW)
                $fatal(1, "%s: MxKxN=%0dx%0dx%0d is not a supported shape", name, m, k, n);
            tests.push_back('{name: name, m: m, n: n, k: k});
        end
    end
    $fclose(fd);
    if (tests.size() == 0) $fatal(1, "No tests found in %s/tests.list", test_dir);

    $display("\n---------------- Golden tests (%0d from %s/tests.list) ----------------", tests.size(), test_dir);
    foreach (tests[i]) run_memory_test(tests[i]);

    // +debug_only runs just the debug add-on test (used by capture_waves.sh for the review waveforms)
    if ($test$plusargs("debug_only")) debug_obs_test(tests[0], tests[0]);
    else if (!$test$plusargs("no_directed")) run_directed_tests(tests);

    $display("\n================ tb_matrix_mult summary ================");
    $display("Tests run                              : %0d", n_tests_run);
    $display("Tests failed                           : %0d", n_tests_failed);
    $display("Assertion / scoreboard failures        : %0d", mm_verif_pkg::sva_errors);
    $display("Golden mismatches (C sim vs SV model)  : %0d", n_golden_errors);
    if (n_tests_failed == 0 && mm_verif_pkg::sva_errors == 0 && n_golden_errors == 0)
        $display("TB RESULT: PASSED");
    else
        $display("TB RESULT: FAILED");
    $display("=========================================================\n");
endtask
